import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { renderChangeBriefMarkdown } from "../../src/core/render/markdown.js";
import { parseChangeBrief } from "../../src/core/validate.js";
import type { ChangeBrief } from "../../src/core/schema.js";
import {
  buildFullPrMarkdown,
  buildGitlabHtml,
  buildGithubHtml,
  type MrPreviewMeta,
} from "../shared/mr-preview.js";

const tiersRoot = dirname(fileURLToPath(import.meta.url));

export const TIER_IDS = ["simple", "medium", "complex"] as const;
export type TierId = (typeof TIER_IDS)[number];

export interface TierConfig {
  id: TierId;
  label: string;
  integrationLevel: string;
  mrTitle: string;
  mrBody: string;
}

export const TIER_CONFIG: Record<TierId, TierConfig> = {
  simple: {
    id: "simple",
    label: "Simple",
    integrationLevel: "1 external HTTP call · 1 internal hook",
    mrTitle: "OPS-12: Slack deploy notifications",
    mrBody:
      "Adds deploy.succeeded → Slack incoming webhook.\n\nCloses OPS-12.",
  },
  medium: {
    id: "medium",
    label: "Medium",
    integrationLevel: "API + Postgres + Redis + email queue",
    mrTitle: "AUTH-88: Magic link login",
    mrBody:
      "Passwordless magic link with Redis sessions.\n\nRelated: email template magic-link-v1.",
  },
  complex: {
    id: "complex",
    label: "Complex",
    integrationLevel: "Multi-repo · S3 · Kafka · OpenSearch · webhooks",
    mrTitle: "catalog-sync-v3: ingest API (MR 1/3)",
    mrBody:
      "First of three MRs for catalog-sync-v3 spec.\n\nSibling: catalog-worker !502, catalog-search !118.",
  },
};

function loadTierBrief(tier: TierId): ChangeBrief {
  const path = join(tiersRoot, tier, "change-brief.json");
  return parseChangeBrief(JSON.parse(readFileSync(path, "utf8")));
}

function briefToMrMeta(brief: ChangeBrief, cfg: TierConfig): MrPreviewMeta {
  const mr = brief.mergeRequest;
  return {
    repo: mr.repo,
    number: mr.number,
    url: mr.url,
    title: cfg.mrTitle,
    body: cfg.mrBody,
    baseSha: mr.baseSha,
    headSha: mr.headSha,
    labels: [`integration-tier:${cfg.id}`, "change-brief:demo"],
  };
}

function workSourceLabel(brief: ChangeBrief): string {
  const ws = brief.workSource;
  if (ws.kind === "jira") return `Jira ${ws.ref}`;
  const rev = ws.specRevision ? `@${ws.specRevision}` : "";
  return `Spec ${ws.specPath ?? ws.ref}${rev}`;
}

export function buildIntegrationTierPreviews(): string[] {
  const outDir = join(tiersRoot, "output");
  mkdirSync(outDir, { recursive: true });
  const written: string[] = [];

  const indexRows: string[] = [];

  for (const tier of TIER_IDS) {
    const cfg = TIER_CONFIG[tier];
    const brief = loadTierBrief(tier);
    const markdown = renderChangeBriefMarkdown(brief);
    const pr = briefToMrMeta(brief, cfg);
    const wsLabel = workSourceLabel(brief);
    const pageTitle = `${pr.repo} !${pr.number} — ${cfg.label} tier`;

    writeFileSync(join(tiersRoot, tier, "change-brief.md"), markdown, "utf8");
    written.push(join(tiersRoot, tier, "change-brief.md"));

    const fullMd = buildFullPrMarkdown(pr, markdown, wsLabel);
    const mdPath = join(outDir, `${tier}-mr.md`);
    const gitlabPath = join(outDir, `${tier}-mr-gitlab.html`);
    const githubPath = join(outDir, `${tier}-mr.html`);

    writeFileSync(mdPath, fullMd, "utf8");
    writeFileSync(gitlabPath, buildGitlabHtml(pr, markdown, wsLabel, pageTitle), "utf8");
    writeFileSync(githubPath, buildGithubHtml(pr, markdown, wsLabel, pageTitle), "utf8");
    written.push(mdPath, gitlabPath, githubPath);

    indexRows.push(
      `| **${cfg.label}** (${cfg.integrationLevel}) | [${tier}-mr-gitlab.html](./${tier}-mr-gitlab.html) | [${tier}-mr.md](./${tier}-mr.md) | [../${tier}/mock-repo/](../${tier}/mock-repo/) |`,
    );
  }

  const indexMd = `# Integration tiers — Change Brief demos

Generated by \`pnpm preview:tiers\`.

Compare how **CBF v0.4** scales from a tiny integration to a multi-repo pipeline. Each row is a fictional MR with a pinned Change Brief note (GitLab-style HTML recommended).

| Tier | GitLab mock | Full MR markdown | Fake repo |
|------|-------------|------------------|-----------|
${indexRows.join("\n")}

## What to look at

| Tier | Brief emphasis |
|------|----------------|
| Simple | Short integration diagram, minimal chronicle, quick checks fit on one screen |
| Medium | Sequence + flowchart, Redis/queue touchpoints, feature flag |
| Complex | Multi-repo merge order, DLQ/Kafka, partial requirements, deep dive |

Edit JSON under \`simple/\`, \`medium/\`, \`complex/\` then re-run \`pnpm preview:tiers\`.
`;
  writeFileSync(join(outDir, "README.md"), indexMd, "utf8");
  written.push(join(outDir, "README.md"));

  return written;
}

if (process.argv[1]?.endsWith("build-previews.ts")) {
  const paths = buildIntegrationTierPreviews();
  console.log("Integration tier previews written:");
  for (const p of paths) console.log(" ", p);
}
