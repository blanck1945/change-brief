import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildFullPrMarkdown,
  buildGithubHtml,
  buildGitlabHtml,
} from "../../shared/mr-preview.js";
import {
  runMockGithubFlow,
  type MockScenarioId,
} from "../../../src/mock/run-github-mock.js";
import type { MockPullRequest } from "../../../src/mock/types.js";

const previewRoot = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(previewRoot, "../../..");

function loadPr(fixturePath: string): MockPullRequest {
  return JSON.parse(
    readFileSync(join(repoRoot, "fixtures", fixturePath), "utf8"),
  ) as MockPullRequest;
}

const SCENARIOS: Array<{
  source: "jira" | "spec";
  scenario: MockScenarioId;
  prFixture: string;
  slug: string;
  workSourceLabel: string;
}> = [
  {
    source: "jira",
    scenario: "jira-proj-1234",
    prFixture: "github/pull-request-842.json",
    slug: "pr-842-jira",
    workSourceLabel: "Jira PROJ-1234",
  },
  {
    source: "spec",
    scenario: "spec-billing-downgrade-v2",
    prFixture: "github/pull-request-901.json",
    slug: "pr-901-spec",
    workSourceLabel: "Spec billing-downgrade-v2",
  },
];

export function buildAllPrPreviews(): string[] {
  const outDir = join(previewRoot, "output");
  mkdirSync(outDir, { recursive: true });

  const written: string[] = [];

  for (const cfg of SCENARIOS) {
    const { brief, markdown } = runMockGithubFlow({
      rootDir: repoRoot,
      source: cfg.source,
      writeArtifacts: true,
    });
    const pr = loadPr(cfg.prFixture);
    const fullMd = buildFullPrMarkdown(pr, markdown, cfg.workSourceLabel);
    const mdPath = join(outDir, `${cfg.slug}.md`);
    const htmlPath = join(outDir, `${cfg.slug}.html`);
    const gitlabHtmlPath = join(outDir, `${cfg.slug}-gitlab.html`);
    const title = `${pr.repo} !${pr.number} — ${cfg.workSourceLabel}`;
    writeFileSync(mdPath, fullMd, "utf8");
    writeFileSync(
      htmlPath,
      buildGithubHtml(pr, markdown, cfg.workSourceLabel, title),
      "utf8",
    );
    writeFileSync(
      gitlabHtmlPath,
      buildGitlabHtml(pr, markdown, cfg.workSourceLabel, title),
      "utf8",
    );
    written.push(mdPath, htmlPath, gitlabHtmlPath);
    void brief;
    void cfg.scenario;
  }

  const indexMd = `# MR / PR previews (mock)

Generated by \`pnpm preview\`.

| Flow | Markdown | GitHub-style | GitLab-style |
|------|----------|--------------|--------------|
| Jira → !842 | [pr-842-jira.md](./pr-842-jira.md) | [pr-842-jira.html](./pr-842-jira.html) | [pr-842-jira-gitlab.html](./pr-842-jira-gitlab.html) |
| Spec → !901 | [pr-901-spec.md](./pr-901-spec.md) | [pr-901-spec.html](./pr-901-spec.html) | [pr-901-spec-gitlab.html](./pr-901-spec-gitlab.html) |

Real GitLab (manual): paste \`fixtures/output/mock-jira-pr-comment.md\` into an MR note. See [\`docs/GITLAB.md\`](../../../docs/GITLAB.md).
`;
  writeFileSync(join(outDir, "README.md"), indexMd, "utf8");
  written.push(join(outDir, "README.md"));

  return written;
}

if (process.argv[1]?.endsWith("build-pr-preview.ts")) {
  const paths = buildAllPrPreviews();
  console.log("PR previews written:");
  for (const p of paths) console.log(" ", p);
}
